"""`uv run python -m kbml.report3 [--models logreg,lgbm,mlp]`: phase 3 on the extended archive.

Grid: model × feature set (`p3_baseline`, `p3_rw`, `p3_all`) × training rows (in scope only, +S/A
2023-24, +tier B, +tier C, and +tier C weighted 0.3). The declared primary (logreg, `p3_rw`, all
rows, unweighted) runs first. Results go to the cache (`report3/results.json`) and to REPORT.md
below the phase 3 generated marker.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

from . import evaluate, features
from .report import REPORT, _row
from .run import with_hltv
from .table import cache_dir, load_table

EXT = Path("D:/Projects/KallBet/target/research-archive-ext")
MARK = "<!-- phase 3 generated by kbml.report3: everything below is rewritten -->"

DATA = [
    ("in scope", {"scope"}, None),
    ("+S/A 2023-24", {"scope", "sa_old"}, None),
    ("+S/A+B", {"scope", "sa_old", "b"}, None),
    ("+S/A+B+C", {"scope", "sa_old", "b", "c"}, None),
    ("+S/A+B+C, C×0.3", {"scope", "sa_old", "b", "c"}, {"c": 0.3}),
]
SETS = ["p3_rw", "p3_baseline", "p3_all"]
PRIMARY = ("logreg", "p3_rw", "+S/A+B+C")


def run_all(archive: Path, models: list[str], log=print) -> dict:
    t0 = time.time()
    m, maps, _ = load_table(archive, log=log)
    m, hltv = with_hltv(m, archive)
    groups = features.resolve("p3_all")
    X, kinds = features.compute(m, maps, groups, hltv)
    log(f"features {X.shape} [{time.time() - t0:.0f}s]")
    by_group = {g: list(features.REGISTRY[g].columns) for g in groups}
    configs = [PRIMARY]
    for model in models:
        for fs in SETS:
            for label, _, _ in DATA:
                if (model, fs, label) != PRIMARY:
                    configs.append((model, fs, label))
    data = {label: (blocks, w) for label, blocks, w in DATA}
    out = {"archive": str(archive), "rows": m["block"].value_counts().to_dict(), "results": []}
    for model, fs, label in configs:
        t = time.time()
        cols = {c: kinds[c] for g in features.SETS[fs] for c in by_group[g]}
        blocks, weights = data[label]
        pred = evaluate.walk_forward(m, X, cols, model, train_blocks=blocks, block_weights=weights)
        s = evaluate.summarize(pred)
        s.update({"model": model, "features": f"{fs} / {label}", "seconds": round(time.time() - t, 1),
                  "train_matches_last": int(pred["train_matches"].max())})
        if "importance" in pred.attrs:
            s["importance"] = pred.attrs["importance"]
        out["results"].append(s)
        log(f"{model:7s} {fs:12s} {label:18s} acc {s['accuracy']['diff']*100:+.1f} pp "
            f"[{s['accuracy']['low']*100:+.1f}, {s['accuracy']['high']*100:+.1f}] ll {s['log_loss']['diff']:+.4f} "
            f"train≤{s['train_matches_last']} [{s['seconds']:.0f}s]")
        f = cache_dir(archive) / "report3"
        f.mkdir(parents=True, exist_ok=True)
        (f / "results.json").write_text(json.dumps(out, indent=1, default=float))
    return out


def markdown(res: dict) -> str:
    rs = res["results"]
    lines = [MARK, "", f"Rows of the extended table by block: {res['rows']}.", ""]
    head = ("| Model | Features / training rows | Matches | Winners picked, anchor → model | Δ accuracy [90%] | Log-loss "
            "| Δ log-loss [90%] |\n|---|---|---:|---|---|---:|---|")
    prim = rs[0]
    a = prim["accuracy"]
    verdict = "picks more winners" if a["low"] > 0 else "does not pick measurably more winners"
    lines += ["## Primary result", "", head, _row(prim), "",
              f"By the declared rule the primary configuration **{verdict}** than the anchor.", "",
              "## Grid (exploratory)", "", head]
    lines += [_row(r) for r in rs]
    lines += ["", "## Width of the accuracy interval by training rows (logreg)", "",
              "| Features | Training rows | Training Matches (last fold) | Δ accuracy | Interval width |",
              "|---|---|---:|---|---:|"]
    for r in rs[1:] + rs[:1]:
        if r["model"] == "logreg":
            fs, label = r["features"].split(" / ")
            acc = r["accuracy"]
            lines.append(f"| {fs} | {label} | {r['train_matches_last']} | {acc['diff']*100:+.1f} pp "
                         f"| {(acc['high'] - acc['low'])*100:.2f} pp |")
    imp = next((r.get("importance") for r in rs if r["model"] == "lgbm" and r["features"] == "p3_all / +S/A+B+C"), None)
    if imp:
        lines += ["", "## LightGBM importance (p3_all, +S/A+B+C)", "", "| Feature | Gain share |", "|---|---:|"]
        lines += [f"| `{k}` | {v*100:.1f}% |" for k, v in sorted(imp.items(), key=lambda kv: -kv[1])[:20]]
    return "\n".join(lines) + "\n"


def write(res: dict):
    text = REPORT.read_text(encoding="utf-8")
    head = text.split(MARK)[0].rstrip() + "\n\n"
    REPORT.write_text(head + markdown(res), encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="kbml.report3")
    ap.add_argument("--models", default="logreg,lgbm,mlp")
    ap.add_argument("--archive", type=Path, default=EXT)
    args = ap.parse_args(argv)
    try:
        sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
    except AttributeError:
        pass
    res = run_all(args.archive, args.models.split(","))
    write(res)


if __name__ == "__main__":
    main()
