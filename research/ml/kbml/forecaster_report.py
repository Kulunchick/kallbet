"""`uv run python -m kbml.forecaster_report [--runs 200000 --jobs 3]` → FORECASTER.md (generated part).

1. The 28-Stage Swiss Pick'em replay (`pickem_check`'s simulation and slip search, unchanged) for
   the anchor, the in-scope models of PICKEM.md and the two ext forecasters, strategies A and B.
2. Calibration of the slip: per Stage and slip, the simulated P(≥5) and expected correct picks
   against the realised outcome; mean predicted vs realised, Brier of the ≥5 event, and paired
   Stage-bootstrap intervals (2000 resamples, 90%, seed 33) against anchor B.
3. Per-Match reliability of the forecasters on the 2087 scored Matches (phase 3 walk-forward).
"""
from __future__ import annotations

import argparse
import json
import pickle
import sys
from collections import defaultdict
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

from . import evaluate, features, stats
from .forecaster import EXT, TRAIN_BLOCKS, pickem_hook

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "FORECASTER.md"
MARK = "<!-- generated by kbml.forecaster_report: everything below is rewritten -->"
MODELS = ["Anchor", "lgbm ext", "logreg ext", "lgbm all", "logreg all", "lgbm baseline", "logreg baseline"]
PRIMARY = ("lgbm ext", "B")
BASE = ("Anchor", "B")


def run_pickem(runs: int, jobs: int, cache: Path):
    from .pickem_check import evaluate_strategy
    from .pickem_data import forecast_all

    rows = list(forecast_all(extra=pickem_hook()))
    tasks = [(stage, m, f[m], runs) for stage, f, *_ in rows for m in MODELS if m in f]
    results = defaultdict(list)
    with ProcessPoolExecutor(jobs) as pool:
        for sid, entries in pool.map(evaluate_strategy, tasks):
            results[sid].extend(entries)
    out = []
    for stage, f, *_ in rows:
        for model, strategy, roles, score, changed, expected, chance in results[stage.id]:
            out.append({"stage": stage.id, "title": stage.title, "cutoff": stage.cutoff, "model": model,
                        "strategy": strategy, "correct": score, "expected": expected, "p5": chance,
                        "changed": changed})
    pairs = {stage.id: {m: np.asarray(f[m]).tolist() for m in MODELS if m in f} for stage, f, *_ in rows}
    cache.write_bytes(pickle.dumps({"rows": out, "pairs": pairs}))
    return out


def _boot(ids, d):
    return stats.event_bootstrap(ids, d, 2000, 0.9, 33)


def stage_tables(rows: list[dict]) -> str:
    by = defaultdict(dict)
    for r in rows:
        by[(r["model"], r["strategy"])][r["stage"]] = r
    stages = sorted({r["stage"] for r in rows})
    base = by[BASE]
    lines = ["| Forecaster | Strategy | Mean correct | Stages ≥5 | Mean predicted P(≥5) | Realised − predicted [90%] "
             "| Brier of ≥5 | Δ Brier vs anchor B [90%] | Δ stages ≥5 vs anchor B [90%] | Expected − realised correct |",
             "|---|---|---:|---:|---:|---|---:|---|---|---:|"]
    summary = {}
    for model in MODELS:
        for strat in ("A", "B"):
            d = by.get((model, strat))
            if not d or len(d) != len(stages):
                continue
            hit = np.array([d[s]["correct"] >= 5 for s in stages], float)
            p5 = np.array([d[s]["p5"] for s in stages])
            cor = np.array([d[s]["correct"] for s in stages], float)
            exp = np.array([d[s]["expected"] for s in stages])
            brier = (p5 - hit) ** 2
            bh = np.array([base[s]["correct"] >= 5 for s in stages], float)
            bb = (np.array([base[s]["p5"] for s in stages]) - bh) ** 2
            gap = _boot(stages, hit - p5)
            db = _boot(stages, brier - bb)
            dh = _boot(stages, hit - bh)
            summary[f"{model} {strat}"] = {"mean_correct": cor.mean(), "hits": int(hit.sum()), "p5": p5.mean(),
                                           "gap": gap, "brier": brier.mean(), "d_brier": db, "d_hits": dh,
                                           "exp_minus_real": (exp - cor).mean()}
            same = (model, strat) == BASE
            lines.append(
                f"| {model} | {strat} | {cor.mean():.2f} | {int(hit.sum())}/{len(stages)} | {p5.mean()*100:.1f}% "
                f"| {gap['mean']*100:+.1f} pp [{gap['low']*100:+.1f}, {gap['high']*100:+.1f}] | {brier.mean():.3f} "
                + ("| — | — " if same else
                   f"| {db['mean']:+.3f} [{db['low']:+.3f}, {db['high']:+.3f}] "
                   f"| {dh['mean']*len(stages):+.0f} stages [{dh['low']*len(stages):+.1f}, {dh['high']*len(stages):+.1f}] ")
                + f"| {(exp - cor).mean():+.2f} |")
    return "\n".join(lines), summary


def reliability(log=print) -> tuple[str, dict]:
    """Phase 3 walk-forward on the 2087 scored Matches: reliability bins (favourite's side)."""
    from .run import with_hltv
    from .table import load_table
    m, mp, _ = load_table(EXT, log=lambda *a: None)
    m, h = with_hltv(m, EXT)
    X, kinds = features.compute(m, mp, features.resolve("p3_all"), h)
    preds = {}
    for name, (model, fset) in {"lgbm ext": ("lgbm", "p3_all"), "logreg ext": ("logreg", "p3_rw")}.items():
        cols = {c: kinds[c] for g in features.SETS[fset] for c in features.REGISTRY[g].columns}
        preds[name] = evaluate.walk_forward(m, X, cols, model, train_blocks=TRAIN_BLOCKS)
    p0 = next(iter(preds.values()))
    y = p0["team_a_won"].to_numpy()
    ev = p0["event_id"].to_numpy()
    series = {"Anchor": p0["anchor"].to_numpy(float), **{k: v["variant"].to_numpy(float) for k, v in preds.items()}}
    edges = np.array([0.5, 0.55, 0.6, 0.65, 0.7, 0.75, 0.8, 0.85, 0.9, 0.95, 1.0001])
    out, summary = [], {}
    head = "| Bin (favourite's P) | " + " | ".join(f"{k}: n, predicted → won" for k in series) + " |"
    out += [head, "|---|" + "---|" * len(series)]
    binned = {}
    for k, p in series.items():
        fav = np.maximum(p, 1 - p)
        won = np.where(p >= 0.5, y, ~y).astype(float)
        idx = np.digitize(fav, edges) - 1
        binned[k] = (fav, won, idx)
        # ECE: Σ_bins n_b/N · |mean won − mean predicted|; over-confidence bootstrapped by Event
        over = fav - won
        summary[k] = {"ece": float(np.sum([abs((won[idx == b] - fav[idx == b]).sum()) for b in range(len(edges) - 1)]) / len(p)),
                      "overconfidence": _boot(ev, over), "brier": float(stats.brier(p, y).mean()),
                      "log_loss": float(stats.log_loss(p, y).mean())}
    for b in range(len(edges) - 1):
        cells = []
        for k in series:
            fav, won, idx = binned[k]
            s = idx == b
            cells.append(f"{int(s.sum())}, {fav[s].mean()*100:.0f}% → {won[s].mean()*100:.0f}%" if s.any() else "0")
        out.append(f"| {edges[b]*100:.0f}–{min(edges[b+1], 1)*100:.0f}% | " + " | ".join(cells) + " |")
    out += ["", "| Forecaster | Log-loss | Brier | ECE | Over-confidence: mean(P favourite − favourite won) [90%] |",
            "|---|---:|---:|---:|---|"]
    for k, s in summary.items():
        o = s["overconfidence"]
        out.append(f"| {k} | {s['log_loss']:.4f} | {s['brier']:.4f} | {s['ece']*100:.1f} pp "
                   f"| {o['mean']*100:+.1f} pp [{o['low']*100:+.1f}, {o['high']*100:+.1f}] |")
    return "\n".join(out), summary


def write(text: str):
    cur = REPORT.read_text(encoding="utf-8")
    head = cur.split(MARK)[0].rstrip() + "\n\n"
    REPORT.write_text(head + MARK + "\n\n" + text, encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="kbml.forecaster_report")
    ap.add_argument("--runs", type=int, default=200000)
    ap.add_argument("--jobs", type=int, default=3)
    ap.add_argument("--reuse", action="store_true", help="reuse the cached Pick'em results")
    args = ap.parse_args(argv)
    try:
        sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
    except AttributeError:
        pass
    cache = Path("D:/Projects/KallBet/target/ml-cache/forecaster-pickem.pkl")
    rows = pickle.loads(cache.read_bytes())["rows"] if args.reuse and cache.exists() else run_pickem(args.runs, args.jobs, cache)
    table, summary = stage_tables(rows)
    rel, rsum = reliability()
    per_stage = ["| Stage | " + " | ".join(f"{m} {s}: correct (P≥5)" for m, s in (BASE, PRIMARY, ("logreg ext", "B"))) + " |",
                 "|---|---|---|---|"]
    by = {(r["stage"], r["model"], r["strategy"]): r for r in rows}
    for sid in sorted({r["stage"] for r in rows}, key=lambda s: next(r["cutoff"] for r in rows if r["stage"] == s)):
        title = next(r["title"] for r in rows if r["stage"] == sid)
        cells = [f"{by[sid, m, s]['correct']} ({by[sid, m, s]['p5']*100:.0f}%)" for m, s in (BASE, PRIMARY, ("logreg ext", "B"))]
        per_stage.append(f"| {title} | " + " | ".join(cells) + " |")
    text = ("## Pick'em: calibration of the slip over the 28 Stages\n\n" + table +
            "\n\nIntervals: paired Stage bootstrap (2000 resamples, 90%, seed 33) over the 28 Stages. "
            "\"Realised − predicted\": share of Stages with ≥5 correct minus the mean simulated P(≥5) "
            "(negative = over-confident). Brier of ≥5: mean of (simulated P(≥5) − [≥5 happened])².\n\n"
            "### Per Stage (strategy B)\n\n" + "\n".join(per_stage) +
            "\n\n## Per-Match reliability on the 2087 scored Matches\n\n"
            "Walk-forward by Event as in phase 3 (ext rows train). Bins by the favourite's probability; "
            "\"won\" = share of those Matches the favourite won.\n\n" + rel + "\n")
    write(text)
    out = Path("D:/Projects/KallBet/target/ml-cache/forecaster-summary.json")
    out.write_text(json.dumps({"stages": summary, "matches": rsum}, indent=1, default=float))
    print(text)


if __name__ == "__main__":
    main()
