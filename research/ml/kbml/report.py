"""`uv run python -m kbml.report [--models logreg,lgbm,mlp] [--archive DIR]`

Runs the primary configuration, every model on all features, and the ablation (phase 1 baseline
plus one HLTV group at a time), and writes the results to the cache (`report/<archive>.json`)
and the generated part of REPORT.md (below the declaration, which it never changes).
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

from . import evaluate, features, paths
from .run import with_hltv
from .table import cache_dir, load_table

MARK = "<!-- generated by kbml.report: everything below is rewritten -->"
REPORT = Path(__file__).resolve().parents[1] / "REPORT.md"


def run_all(archive: Path, models: list[str], log=print) -> dict:
    t0 = time.time()
    matches, maps, _ = load_table(archive, log=log)
    matches, hltv = with_hltv(matches, archive)
    groups = features.resolve("full")
    X, kinds = features.compute(matches, maps, groups, hltv)
    log(f"features: {X.shape} [{time.time() - t0:.0f}s]")
    by_group = {g: list(features.REGISTRY[g].columns) for g in groups}

    def cols(gs):
        return {c: kinds[c] for g in gs for c in by_group[g]}

    configs = []
    for model in models:
        configs.append((model, "full", groups))
        configs.append((model, "baseline", features.SETS["baseline"]))
        for g in features.SETS["hltv"]:
            configs.append((model, f"baseline+{g}", features.SETS["baseline"] + [g]))
    out = {"archive": str(archive), "matches": int(len(matches)), "results": []}
    for model, label, gs in configs:
        t = time.time()
        pred = evaluate.walk_forward(matches, X, cols(gs), model)
        s = evaluate.summarize(pred)
        s.update({"model": model, "features": label, "seconds": round(time.time() - t, 1)})
        tier_s = pred[pred["tier"] == "s"]
        s["tier_s"] = evaluate.summarize(tier_s) if len(tier_s) else None
        if "importance" in pred.attrs:
            s["importance"] = pred.attrs["importance"]
        out["results"].append(s)
        log(f"{model:7s} {label:24s} acc {s['accuracy']['diff']*100:+.1f} pp "
            f"[{s['accuracy']['low']*100:+.1f}, {s['accuracy']['high']*100:+.1f}]  "
            f"ll {s['log_loss']['diff']:+.4f}  [{s['seconds']:.0f}s]")
    return out


def _row(r):
    a, ll = r["accuracy"], r["log_loss"]
    return (f"| {r['model']} | {r['features']} | {r['matches']} | {a['anchor']*100:.1f}% → {a['model']*100:.1f}% "
            f"| {a['diff']*100:+.1f} pp [{a['low']*100:+.1f}, {a['high']*100:+.1f}] "
            f"| {ll['model']:.4f} | {ll['diff']:+.4f} [{ll['low']:+.4f}, {ll['high']:+.4f}] |")


HEAD = ("| Model | Features | Matches | Winners picked, anchor → model | Δ accuracy [90%] | Log-loss "
        "| Δ log-loss [90%] |\n|---|---|---:|---|---|---:|---|")


def markdown(res: dict) -> str:
    rs = res["results"]
    find = lambda m, f: next((r for r in rs if r["model"] == m and r["features"] == f), None)  # noqa: E731
    lines = [MARK, "", f"Archive: `{res['archive']}`. Anchor log-loss on these Matches: "
             f"{rs[0]['log_loss']['anchor']:.4f}, accuracy {rs[0]['accuracy']['anchor']*100:.2f}%.", ""]
    prim = find("logreg", "full")
    if prim:
        a = prim["accuracy"]
        verdict = "picks more winners" if a["low"] > 0 else "does not pick measurably more winners"
        lines += ["## Primary result", "", HEAD, _row(prim), "",
                  f"By the declared rule the primary configuration **{verdict}** than the anchor "
                  f"(interval [{a['low']*100:+.1f}, {a['high']*100:+.1f}] pp).", ""]
    lines += ["## Every model on all features (exploratory)", "", HEAD]
    lines += [_row(r) for r in rs if r["features"] == "full"]
    lines += ["", "## Ablation: phase 1 baseline plus one HLTV group (exploratory)", "", HEAD]
    lines += [_row(r) for r in rs if r["features"] != "full"]
    lines += ["", "## Tier S slice (exploratory)", "", HEAD]
    for r in rs:
        if r["features"] == "full" and r.get("tier_s"):
            lines.append(_row(dict(r["tier_s"], model=r["model"], features="full, tier S")))
    imp = (find("lgbm", "full") or {}).get("importance")
    if imp:
        top = sorted(imp.items(), key=lambda kv: -kv[1])
        lines += ["", "## LightGBM feature importance (all features)", "",
                  "Share of total split gain, averaged over the walk-forward fits (weighted by the Matches each "
                  "fit predicted).", "", "| Feature | Gain share |", "|---|---:|"]
        lines += [f"| `{k}` | {v*100:.1f}% |" for k, v in top[:25]]
    return "\n".join(lines) + "\n"


P3 = "# Phase 3:"


def write_report(res: dict, conclusion: str | None = None):
    """Rewrites the phase 2 generated part only (between its marker and the phase 3 heading)."""
    text = REPORT.read_text(encoding="utf-8")
    head = text.split(MARK)[0].rstrip() + "\n\n"
    tail = text[text.index(P3):] if P3 in text else ""
    body = markdown(res)
    REPORT.write_text(head + body + (("\n" + conclusion) if conclusion else "") + ("\n" + tail if tail else ""),
                      encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="kbml.report")
    ap.add_argument("--models", default="logreg,lgbm,mlp")
    ap.add_argument("--archive", type=Path, default=paths.ARCHIVE)
    ap.add_argument("--no-write", action="store_true")
    args = ap.parse_args(argv)
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except AttributeError:
        pass
    res = run_all(args.archive, args.models.split(","))
    out = cache_dir(args.archive) / "report"
    out.mkdir(parents=True, exist_ok=True)
    (out / "results.json").write_text(json.dumps(res, indent=1, default=float))
    if not args.no_write:
        write_report(res)
    print(f"results: {out / 'results.json'}")


if __name__ == "__main__":
    main()
