"""`uv run python -m kbml.signals_report`: SIGNALS.md generated part from `signals/results.json` and
`signals/spa.json` (run `kbml.signals` and `kbml.spa` first). Everything below the marker is rewritten."""
from __future__ import annotations

import json
from pathlib import Path

from .forecaster import EXT
from .table import cache_dir

REPORT = Path(__file__).resolve().parents[1] / "SIGNALS.md"
MARK = "<!-- generated by kbml.signals_report: everything below is rewritten -->"


def _iv(x, scale=1.0, d=4, unit=""):
    v = x.get("diff", x.get("mean"))
    f = f"{{:+.{d}f}}"
    return f"{f.format(v * scale)}{unit} [{f.format(x['low'] * scale)}, {f.format(x['high'] * scale)}]"


HEAD = ("| Configuration | Subset | Matches (Events) | Log-loss base → variant | Δ log-loss [90%] | Δ Brier [90%] "
        "| Δ resolution [90%] | Accuracy base → variant | Δ accuracy [90%] |\n|---|---|---:|---|---|---|---|---|---|")


def row(r, label=None):
    ll, br, ac, rs = r["log_loss"], r["brier"], r["accuracy"], r["resolution"]
    return (f"| {label or r['name']} | {r.get('subset', '')} | {r['matches']} ({r['events']}) | {ll['base']:.4f} → {ll['variant']:.4f} "
            f"| {_iv(ll)} | {_iv(br)} | {_iv(rs, d=4)} | {ac['base']*100:.1f}% → {ac['variant']*100:.1f}% "
            f"| {_iv(ac, 100, 1, ' pp')} |")


def markdown(res, sp) -> str:
    p = res["primary"]
    ll = p["log_loss"]
    verdict = "improves" if ll["high"] < 0 else "does not measurably improve"
    L = [MARK, "", "## Primary result", "", HEAD, row(p, "lgbm-ext + A (core)"), "",
         f"By the declared rule, two-stage market fusion **{verdict}** `lgbm-ext` on the priced Matches "
         f"(Δ log-loss interval [{ll['low']:+.4f}, {ll['high']:+.4f}]). Stage 2 fell back to `lgbm-ext` "
         f"for {p['fallback_events']} of the 21 priced Events (fewer than 100 earlier priced training Matches).", ""]
    rows = res["rows"]
    for sig, title in (("A", "A: market fusion (exploratory variants)"), ("B", "B: Bo3 veto, empirical Bayes"),
                       ("C", "C: OpenSkill player ratings"), ("D", "D: travel")):
        L += [f"## {title}", "", HEAD]
        L += [row(r) for r in rows if r["signal"] == sig]
        L.append("")
        if sig == "A":
            n = res["notes"]
            dv = n["devig"]
            L += [f"De-vig of the last pre-cutoff Pinnacle price as a forecast on its own ({dv['matches']} scored "
                  f"Matches, mean overround {n['pinnacle_overround']:.3f}):", "",
                  "| Method | Log-loss | Brier | Δ log-loss vs proportional [90%] |", "|---|---:|---:|---|"]
            for k in ("proportional", "power", "shin"):
                L.append(f"| {k} | {dv[k]['log_loss']:.4f} | {dv[k]['brier']:.4f} | {_iv(dv[k]['vs_proportional'], d=5)} |")
            c = n["clv"]
            L += ["", f"CLV-style metric ({c['matches']} scored Matches with an early and a closing price; early = "
                  "about 12 h before the cutoff, close = last pre-cutoff price, chain order of sources). "
                  "CLV = sign(model − early) × (close − early) in logit units; the model is stage 1 (no market input).", "",
                  "| Stage 1 of | Mean CLV (logit) [90%] | Share of moved lines that moved toward the model [90%] | Lines moved "
                  "| Log-loss close − early [90%] |", "|---|---|---|---:|---|"]
            for k in ("lgbm-ext", "logreg-ext"):
                x = c[k]
                L.append(f"| {k} | {_iv(x['mean_clv_logit'])} | {_iv(x['share_toward_model'], 100, 1, '%')} | {x['moved']} "
                         f"| {_iv(x['close_minus_early_logloss'])} |")
            L.append("")
        if sig == "B":
            v = res["notes"]["veto_standalone"]
            L += [f"The simulation alone against the anchor on the {v['matches']} scored Bo3s with a simulated veto "
                  "(the lab's `bo3_veto_sim`, which blends its simulation with the market, picked −2.8 pp [−4.5, −1.4] "
                  "on 1,771 Bo3s):", "", HEAD.replace("Configuration", "Forecast vs anchor")]
            for k in [k for k in v if k != "matches"]:
                L.append(row({**v[k], "subset": "bo3"}, k))
            L += ["", "Active map-pool changes the point-in-time pool detector found in our own vetoes (the seven "
                  "maps most frequent in the last 14 days of released vetoes; date = first cutoff that sees the change):", "",
                  "| Seen from | Map in | Map out |", "|---|---|---|"]
            L += [f"| {d} | {', '.join(a)} | {', '.join(o)} |" for d, a, o in res["notes"]["pool_changes"]]
            L.append("")
    L += ["## E: multiple-testing control (Hansen SPA, Event block bootstrap)", "",
          f"Configurations: phase 2 {sp['counts']['phase2']}, phase 3 {sp['counts']['phase3']} (which include "
          f"phase 4's two forecasters), phase 5 {sp['counts']['phase5']}. 2000 Event resamples, seed 33; survivors = "
          "stepwise SPA at α = 0.10.", "",
          "| Family | Loss | K | Best (mean loss gain) | p (consistent) | p (lower) | p (upper, RC) | Survivors |",
          "|---|---|---:|---|---:|---:|---:|---|"]
    for k, v in sp.items():
        if k == "counts":
            continue
        fam, loss = k.split("/")
        surv = ", ".join(f"`{s}`" for s in v["survivors"][:8]) + (f" (+{len(v['survivors']) - 8} more)" if len(v["survivors"]) > 8 else "")
        L.append(f"| {fam} | {loss} | {v['configurations']} | `{v['best']}` ({v['best_mean_diff']:+.4f}) | {v['p_consistent']:.3f} "
                 f"| {v['p_lower']:.3f} | {v['p_upper']:.3f} | {surv or 'none'} ({len(v['survivors'])}) |")
    t = res["notes"].get("timings", {})
    if t:
        L += ["", "Veto integration timings: " + "; ".join(f"{x['matches']} Matches on {x['device']} in {x['seconds']} s"
                                                        for x in t.get("veto_series", [])) + "."]
    L += ["", f"Coverage on the 2,087 scored Matches: OpenSkill lineups {res['notes']['openskill_cover']*100:.0f}%, "
          f"travel (both teams located) {res['notes']['travel_cover']*100:.0f}%, simulated Bo3 vetoes "
          f"{res['notes']['veto_cover_bo3']:.0f} Matches."]
    return "\n".join(L) + "\n"


def write():
    cache = cache_dir(EXT) / "signals"
    res = json.loads((cache / "results.json").read_text())
    sp = json.loads((cache / "spa.json").read_text())
    text = REPORT.read_text(encoding="utf-8")
    head = text.split(MARK)[0].rstrip() + "\n\n"
    REPORT.write_text(head + markdown(res, sp), encoding="utf-8")


if __name__ == "__main__":
    write()
