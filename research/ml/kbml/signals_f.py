"""`kbml.signals_f`: phase 5b (SIGNALS.md): rolling player history F on W5's recovered HLTV links.

Run with the W5 environment (separate cache root, explicit link list):

    $env:KBML_CACHE="D:/Projects/KallBet/target/ml-cache-w5"
    $env:KBML_HLTV_LINKS="D:/Projects/KallBet/target/research-archive-ext/derived/recovery/links.tsv"
    uv run python -m kbml.signals_f

Primary first (`lgbm-ext` + F vs `lgbm-ext`, both on the recovered links), then the exploratory rows,
the effect of the links on the bases (against phase 5's bases from the default cache), and the SPA
families with F added. Writes `signals_f/{preds.parquet,results.json}` under the W5 cache and the part
of SIGNALS.md below its marker.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

from . import evaluate, features, fusion, paths, spa, stats
from . import features_signals as fs
from .forecaster import EXT
from .run import with_hltv
from .signal_eval import compare
from .signals_report import REPORT, row
from .table import cache_dir, load_table

PLAYER_TABLE = EXT / "derived" / "rating-audit" / "hltv_player_match_stats.parquet"
OLD_CACHE = Path("D:/Projects/KallBet/target/ml-cache") / EXT.name
BASES = {"lgbm-ext": ("lgbm", "p3_all"), "logreg-ext": ("logreg", "p3_rw")}
MARK_F = "<!-- phase 5b generated by kbml.signals_f: everything below is rewritten -->"


def _cols(fset, kinds, add=(), drop=()):
    cols = [c for g in features.SETS[fset] if g not in drop for c in features.REGISTRY[g].columns]
    cols += [c for g in add for c in features.REGISTRY[g].columns]
    return {c: kinds[c] for c in cols}


def run(log=print):
    assert paths.LINKS, "set KBML_HLTV_LINKS (and KBML_CACHE) to W5's links"
    t0 = time.time()
    cache = cache_dir(EXT)
    out_dir = cache / "signals_f"
    out_dir.mkdir(parents=True, exist_ok=True)
    m, maps, meta = load_table(EXT, log=log)
    m, hltv = with_hltv(m, EXT)
    # parity: the scored set and its anchor are those of the default table
    old = pd.read_parquet(OLD_CACHE / "matches.parquet")
    so = old[old.in_scope & old.anchor_p.notna()].set_index("match_id")
    sn = m[m.in_scope & m.anchor_p.notna()].set_index("match_id")
    assert set(so.index) == set(sn.index) and len(sn) == 2087, "scored set changed"
    assert np.allclose(so.loc[sn.index, "anchor_p"], sn["anchor_p"]), "anchor changed"
    cover = {"linked_all_new": int(m["hltv_file"].notna().sum()), "linked_all_old": int(old["hltv_file"].notna().sum()),
             "linked_scored_new": int(sn["hltv_file"].notna().sum()), "linked_scored_old": int(so["hltv_file"].notna().sum())}
    log(f"links: {cover}")
    fx = out_dir / "X.parquet"
    groups = features.resolve("p3_all") + ["player_hist"]
    kinds = {c: k for g in groups for c, k in features.REGISTRY[g].columns.items()}
    timings = {}
    if fx.exists():
        X = pd.read_parquet(fx)
    else:
        t = time.time()
        fs.PlayerHist.maps = fs.load_player_maps(PLAYER_TABLE)
        timings["player_table_load_s"] = round(time.time() - t, 1)
        t = time.time()
        X, _ = features.compute(m, maps, groups, hltv)
        timings["features_s"] = round(time.time() - t, 1)
        X.to_parquet(fx)
        log(f"features {X.shape} [{timings['features_s']}s]")
    res = {"cover": cover, "rows": [], "timings": timings}
    preds, base_pred = {}, {}
    for name, (model, fset) in BASES.items():
        pred = evaluate.walk_forward(m, X, _cols(fset, kinds), model, train_blocks=fusion.TRAIN_BLOCKS, log=lambda *_: None)
        base_pred[name] = pred
        preds[f"{name} (W5 links)"] = pred["variant"].to_numpy()
    ref = base_pred["lgbm-ext"]
    y, ev, mk = ref["team_a_won"].to_numpy(), ref["event_id"].to_numpy(), ref["has_market"].to_numpy()

    def summ(name, pv, pb, mask=None, subset="all", base=None):
        sel = np.ones(len(ref), bool) if mask is None else mask
        return {"name": name, "subset": subset, "base": base, **compare(pv[sel], pb[sel], y[sel], ev[sel])}

    # ---- primary
    t = time.time()
    pf = evaluate.walk_forward(m, X, _cols("p3_all", kinds, ["player_hist"]), "lgbm", train_blocks=fusion.TRAIN_BLOCKS,
                               log=lambda *_: None)["variant"].to_numpy()
    timings["lgbm_walk_forward_s"] = round(time.time() - t, 1)
    pb = base_pred["lgbm-ext"]["variant"].to_numpy()
    preds["lgbm-ext + F (W5 links)"] = pf
    res["primary"] = summ("lgbm-ext + F", pf, pb)
    P = res["primary"]["log_loss"]
    log(f"PRIMARY Δ log-loss {P['diff']:+.4f} [{P['low']:+.4f}, {P['high']:+.4f}]")
    res["rows"] += [res["primary"], summ("lgbm-ext + F", pf, pb, mk, "market")]
    # ---- exploratory
    for name, label, add, drop in (("logreg-ext", "logreg-ext + F", ["player_hist"], ()),
                                   ("lgbm-ext", "lgbm-ext + F − players", ["player_hist"], ("players",))):
        model, fset = BASES[name]
        pv = evaluate.walk_forward(m, X, _cols(fset, kinds, add, drop), model, train_blocks=fusion.TRAIN_BLOCKS,
                                   log=lambda *_: None)["variant"].to_numpy()
        preds[f"{label} (W5 links)"] = pv
        pbase = base_pred[name]["variant"].to_numpy()
        res["rows"] += [summ(label, pv, pbase), summ(label, pv, pbase, mk, "market")]
    # ---- effect of the recovered links on the bases (phase 5 bases, default linker)
    old_p = pd.read_parquet(OLD_CACHE / "signals" / "preds.parquet").set_index("match_id").loc[ref["match_id"]]
    res["links_effect"] = [summ(f"{n} W5 links vs old links", base_pred[n]["variant"].to_numpy(), old_p[n].to_numpy())
                           for n in BASES]
    # ---- SPA with F added
    res["spa"] = spa_with_f(ref, preds)
    fr = ref[["match_id", "event_id", "team_a_won", "anchor", "has_market"]].copy()
    for k, v in preds.items():
        fr[k] = v
    fr.to_parquet(out_dir / "preds.parquet", index=False)
    res["seconds"] = round(time.time() - t0)
    (out_dir / "results.json").write_text(json.dumps(res, indent=1, default=float))
    return res


def spa_with_f(ref, preds):
    p2 = pd.read_parquet(OLD_CACHE / "spa" / "phase2.parquet")
    p3 = pd.read_parquet(OLD_CACHE / "spa" / "phase3.parquet")
    p5 = pd.read_parquet(OLD_CACHE / "signals" / "preds.parquet")
    drop = ["event_id", "team_a_won", "anchor", "has_market"]
    f = p3.merge(p2.drop(columns=drop), on="match_id").merge(p5.drop(columns=drop), on="match_id")
    f = f.set_index("match_id").loc[ref["match_id"]].reset_index()
    for k, v in preds.items():
        f[k] = v
    y = f["team_a_won"].to_numpy().astype(bool)
    ev = f["event_id"].to_numpy()
    meta = {"match_id", "event_id", "team_a_won", "anchor", "has_market"}
    configs = [c for c in f.columns if c not in meta and c not in ("lgbm-ext", "logreg-ext")]
    out = {"configurations": len(configs)}
    for kind in ("log_loss", "accuracy"):
        fn = stats.log_loss if kind == "log_loss" else (lambda p, a: 1.0 - stats.correct(p, a))
        L = {c: fn(f[c].to_numpy(float), y) for c in configs}
        out[f"all_vs_anchor/{kind}"] = spa.spa(ev, fn(f["anchor"].to_numpy(float), y), L)
        # add-ons against their own base: phase 5 (old links) and F (W5 links)
        diffs = {}
        for c in configs:
            if " + " not in c or "stage 1" in c:
                continue
            base = c.split(" + ")[0]
            bcol = f"{base} (W5 links)" if c.endswith("(W5 links)") else base
            diffs[c] = L[c] - fn(f[bcol].to_numpy(float), y)
        out[f"addons_vs_base/{kind}"] = spa.spa(ev, np.zeros(len(f)), diffs)
    return out


def markdown(res) -> str:
    from .signals_report import HEAD
    P = res["primary"]["log_loss"]
    verdict = "improves" if P["high"] < 0 else "does not measurably improve"
    c = res["cover"]
    L = [MARK_F, "", "## Phase 5b result: rolling player history (F)", "",
         f"Links: {c['linked_all_new']} Matches of the extended table linked to an HLTV page "
         f"(default linker: {c['linked_all_old']}), {c['linked_scored_new']} of the 2,087 scored Matches "
         f"(default: {c['linked_scored_old']}). Scored set and anchor unchanged (checked).", "",
         "### Primary", "", HEAD, row(res["primary"], "lgbm-ext + F (W5 links)"), "",
         f"By the declared rule, F **{verdict}** `lgbm-ext` (Δ log-loss interval [{P['low']:+.4f}, {P['high']:+.4f}]).", "",
         "### Exploratory", "", HEAD]
    L += [row(r) for r in res["rows"][1:]]
    L += ["", "### Effect of the recovered links on the bases (W5 links − default linker, same Matches)", "", HEAD]
    L += [row({**r, "subset": "all"}) for r in res["links_effect"]]
    L += ["", f"### SPA with F (Event block bootstrap, 2000 resamples, seed 33; {res['spa']['configurations']} configurations)",
          "", "| Family | Loss | K | Best (mean loss gain) | p (consistent) | p (lower) | p (upper, RC) | Survivors |",
          "|---|---|---:|---|---:|---:|---:|---|"]
    for k, v in res["spa"].items():
        if k == "configurations":
            continue
        fam, loss = k.split("/")
        surv = ", ".join(f"`{s}`" for s in v["survivors"][:5]) + (f" (+{len(v['survivors']) - 5} more)" if len(v["survivors"]) > 5 else "")
        L.append(f"| {fam} | {loss} | {v['configurations']} | `{v['best']}` ({v['best_mean_diff']:+.4f}) | {v['p_consistent']:.3f} "
                 f"| {v['p_lower']:.3f} | {v['p_upper']:.3f} | {surv or 'none'} ({len(v['survivors'])}) |")
    t = res["timings"]
    if t:
        L += ["", "Timings (CPU; LightGBM's build has no GPU learner and the rolling features are per-Match "
              "dictionary updates, so nothing here runs on the GPU): " + ", ".join(f"{k} {v}" for k, v in t.items()) + "."]
    return "\n".join(L) + "\n"


def write(res):
    text = REPORT.read_text(encoding="utf-8")
    head = text.split(MARK_F)[0].rstrip() + "\n\n"
    REPORT.write_text(head + markdown(res), encoding="utf-8")


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
    except AttributeError:
        pass
    write(run())


if __name__ == "__main__":
    main()
