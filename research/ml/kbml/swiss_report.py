def fmt_ci(d, scale=1.0, digits=3, signed=True):
    f = f"{{:+.{digits}f}}" if signed else f"{{:.{digits}f}}"
    return f"{f.format(d['mean'] * scale)} [{f.format(d['low'] * scale)}, {f.format(d['high'] * scale)}]"


def table(inputs, results, anchor, logreg, stages=None):
    lines = ["| Variant | Mean correct | Stages ≥5 | Predicted P(≥5) | Realised − predicted [90%] | Brier of ≥5 "
             "| Δ Brier vs logreg-ext B [90%] | Δ Stages ≥5 vs anchor B [90%] | Δ Stages ≥5 vs logreg-ext B [90%] "
             "| Expected − realised correct |", "|---|---:|---:|---:|---|---:|---|---|---|---:|"]
    out = {}
    for name, rows in results:
        s = S.summarise(inputs, rows, anchor, logreg, stages)
        out[name] = s
        n = s["n"]
        lines.append(
            f"| {name} | {s['correct']:.2f} | {s['hits']}/{n} | {s['p5']*100:.1f}% | "
            f"{fmt_ci(s['real_minus_pred'], 100, 1)} pp | {s['brier']:.3f} | {fmt_ci(s['d_brier_logreg'])} | "
            f"{fmt_ci(s['d_hits_anchor'], n, 1)} | {fmt_ci(s['d_hits_logreg'], n, 1)} | {s['exp_minus_real']:+.2f} |")
    return "\n".join(lines), out


