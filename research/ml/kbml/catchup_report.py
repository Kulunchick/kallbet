"""`uv run python -m kbml.catchup_report` → CATCHUP.md (generated part).

Plain, static 40-60, re-tuned static (walk-forward window) and DP bots, with anchor and lgbm-ext
probabilities, on the 57 in-scope Events of the research snapshot: 2000 paired trials, seed 33, the
draws of `kbml.catchup`. Intervals: 90% Hoeffding over trials (as catch-up.md) and, for differences,
an Event-clustered bootstrap (2000 resamples, seed 33) of the trials grouped by drawn Event.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

from . import catchup, catchup_dp as dp, catchup_probs, evaluate, paths, stats

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "CATCHUP.md"
MARK = "<!-- generated by kbml.catchup_report: everything below is rewritten -->"
SCENARIOS = [("favourite follower, 10% noise", "favourite", 0.10), ("favourite follower, 25% noise", "favourite", 0.25),
             ("market follower", "market", None)]
SIZES = (4, 12)
SOURCES = ("anchor", "lgbm ext")
WINDOWS = [0.50] + [round(0.52 + 0.02 * i, 2) for i in range(10)]  # 0.50 = never flip
TUNE_TRIALS = 400


def load():
    from .table import load_table
    m, _, _ = load_table(log=lambda *a: None)
    probs = catchup_probs.load()
    events = catchup.events_from(m, {"lgbm ext": probs}, scope_only=True)
    s = m[m["in_scope"]]
    ids = sorted(int(e) for e in s["event_id"].unique())
    infos = evaluate.event_infos(m)
    return events, ids, infos


def earlier(ids, infos, e):
    return [j for j, jid in enumerate(ids) if infos[jid].trains(infos[ids[e]])]


def dp_tables(events, ids, infos, src, follower, eps, n_opp):
    rmax = max(len(g) for g in events) + 2
    out = {}
    for e, eid in enumerate(ids):
        prior = earlier(ids, infos, e)
        games = [g for j in prior for g in events[j]]
        types = dp.match_types(games, src, follower)
        if len(games) < 100 or len(types[0]) == 0:
            types = dp.PRIOR
        out[eid] = dp.build(n_opp, eps, *types, rmax)
    return out


def tune(events, ids, infos, src, size, noise):
    """Per Event: the window maximising mean P(1st) over Events that ended before it began."""
    M = np.zeros((len(events), len(WINDOWS)))
    bots = [dp.Window(src, hi) for hi in WINDOWS]
    for j in range(len(events)):
        rng = stats.SeededRng(1000 + j)
        first = np.zeros(len(WINDOWS))
        for _ in range(TUNE_TRIALS):
            first += np.array(dp.simulate(events[j], size, noise, rng, bots)) == 1
        M[j] = first / TUNE_TRIALS
    chosen = {}
    for e, eid in enumerate(ids):
        prior = earlier(ids, infos, e)
        chosen[eid] = 0.60 if not prior else WINDOWS[int(np.argmax(M[prior].mean(axis=0)))]
    return chosen


def hoef(v, lo, hi):
    return catchup.hoeffding(v, lo, hi)


def evaluate_all(events, ids, infos, trials=2000, log=print):
    res = {}
    for label, follower, noise in SCENARIOS:
        for size in SIZES:
            t0 = time.time()
            n_opp = size - 1
            eps = 0.0 if noise is None else noise
            bots, names = [], []
            extra = {}
            for src in SOURCES:
                tabs = dp_tables(events, ids, infos, src, follower, eps, n_opp)
                chosen = tune(events, ids, infos, src, size, noise)
                extra[src] = {"windows": chosen}
                bots += [dp.Plain(src), dp.Window(src), dp.Window(src, per_event=chosen), dp.DP(src, tabs)]
                names += [(src, "plain"), (src, "static 40-60"), (src, "re-tuned window"), (src, "DP")]
            if noise is not None:  # exploratory: the DP built for the other noise level
                wrong = 0.25 if noise == 0.10 else 0.10
                bots.append(dp.DP("lgbm ext", dp_tables(events, ids, infos, "lgbm ext", follower, wrong, n_opp)))
                names.append(("lgbm ext", f"DP built for {wrong:.0%} noise"))
            places, drawn = dp.run(events, ids, bots, size, noise, trials)
            first = (places == 1).astype(float)
            rows = {}
            for i, (src, pol) in enumerate(names):
                base = names.index((src, "plain"))
                d = first[:, i] - first[:, base]
                dpl = places[:, i] - places[:, base]
                rows[(src, pol)] = {
                    "first": hoef(first[:, i], 0, 1), "place": hoef(places[:, i], 1, size),
                    "d_first": hoef(d, -1, 1), "d_first_boot": stats.event_bootstrap(drawn, d),
                    "d_place": hoef(dpl, -(size - 1), size - 1), "d_place_boot": stats.event_bootstrap(drawn, dpl),
                }
            flips = {f"{b.src}": b.flips / trials for b in bots if isinstance(b, dp.DP)}
            res[(label, size)] = {"rows": rows, "flips_per_trial": flips,
                                  "windows": {s: extra[s]["windows"] for s in SOURCES}}
            log(f"{label}, {size}: {time.time() - t0:.0f}s")
    return res


def fmt(t, k=3):
    return f"{t[0]:.{k}f} [{t[1]:.{k}f}, {t[2]:.{k}f}]"


def fmtd(t, k=3):
    return f"{t[0]:+.{k}f} [{t[1]:+.{k}f}, {t[2]:+.{k}f}]"


def markdown(res, n_events, trials) -> str:
    out = [f"{n_events} in-scope Events, {trials} paired trials, seed 33 (the draws of `kbml.catchup`). "
           "P(1st) counts a shared first place. Brackets: 90% Hoeffding over the trials (Monte Carlo only, "
           "conditional on these Events and opponents, as catch-up.md); Δ columns also give an "
           "Event-clustered bootstrap (trials grouped by drawn Event, 2000 resamples, seed 33). Δ is "
           "against the plain bot with the same probabilities.", ""]
    for (label, size), r in res.items():
        out += [f"### {label}, {size} members", "",
                "| Probabilities | Policy | P(1st) | Mean place | Δ P(1st) vs plain (Hoeffding) | Δ P(1st) (Event bootstrap) | Δ mean place (Hoeffding) |",
                "|---|---|---|---|---|---|---|"]
        for (src, pol), v in r["rows"].items():
            if pol == "plain":
                out.append(f"| {src} | {pol} | {fmt(v['first'])} | {fmt(v['place'], 2)} | — | — | — |")
                continue
            b = v["d_first_boot"]
            out.append(f"| {src} | {pol} | {fmt(v['first'])} | {fmt(v['place'], 2)} | {fmtd(v['d_first'])} "
                       f"| {b['mean']:+.3f} [{b['low']:+.3f}, {b['high']:+.3f}] | {fmtd(v['d_place'], 2)} |")
        fl = ", ".join(f"{k} {v:.1f}" for k, v in r["flips_per_trial"].items())
        ws = {s: np.bincount([dp_i for dp_i in [WINDOWS.index(w) for w in r["windows"][s].values()]],
                             minlength=len(WINDOWS)) for s in SOURCES}
        wtxt = "; ".join(f"{s}: " + ", ".join(f"{WINDOWS[i]:.2f}×{c}" for i, c in enumerate(ws[s]) if c)
                         for s in SOURCES)
        out += ["", f"DP flips per trial (all DP bots, in order): {fl}. Re-tuned windows chosen (upper "
                f"bound of the favourite's probability, 0.50 = never flip; Events): {wtxt}.", ""]
    return "\n".join(out)


def write(text: str):
    cur = REPORT.read_text(encoding="utf-8")
    head = cur.split(MARK)[0].rstrip() + "\n\n"
    REPORT.write_text(head + MARK + "\n\n" + text + "\n", encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="kbml.catchup_report")
    ap.add_argument("--trials", type=int, default=2000)
    args = ap.parse_args(argv)
    try:
        sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
    except AttributeError:
        pass
    events, ids, infos = load()
    res = evaluate_all(events, ids, infos, args.trials)
    text = markdown(res, len(events), args.trials)
    write(text)
    js = {f"{k[0]} | {k[1]}": {"rows": {f"{s} | {p}": v for (s, p), v in r["rows"].items()},
                               "flips_per_trial": r["flips_per_trial"]} for k, r in res.items()}
    (paths.CACHE / "catchup-dp-results.json").write_text(json.dumps(js, indent=1, default=float))
    print(text)


if __name__ == "__main__":
    main()
